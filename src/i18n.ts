/* QPi SDK 插件 — 全局中英双语资源
   使用方式: import { t, isZh } from './i18n'; t('key')
   语言默认跟随 VS Code UI 语言 (vscode.env.language);
   用户可通过标题栏语言按钮覆盖 (setLanguage), 覆盖值由 extension 持久化。 */
import * as vscode from 'vscode';

export type Lang = 'zh' | 'en';

/** 用户手动选择的语言; null = 未选择, 跟随 IDE 语言 */
let override: Lang | null = null;

/** 按 IDE 语言判定 */
function byIde(): Lang {
  return (vscode.env.language || 'en').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

/** 当前生效语言: 用户覆盖优先, 否则跟随 IDE */
export function currentLanguage(): Lang {
  return override ?? byIde();
}

/** 设置/清除用户覆盖 (null = 恢复跟随 IDE) */
export function setLanguage(lang: Lang | null): void {
  override = lang;
}

export function isZh(): boolean {
  return currentLanguage() === 'zh';
}

